SUPERSAMPLE = 2


def _curve(points, closed=False):
    """Round the hand-traced control points into a Catmull–Rom spline."""
    if closed:
        padded = [points[-1], *points, points[0], points[1]]
    else:
        padded = [points[0], *points, points[-1]]
    for a, b, c, d in zip(padded, padded[1:], padded[2:], padded[3:]):
        for step in range(8):
            t = step / 8
            yield tuple(
                round(SUPERSAMPLE * (2 * v + (-u + w) * t
                      + (2 * u - 5 * v + 4 * w - z) * t**2
                      + (-u + 3 * v - 3 * w + z) * t**3) / 2)
                for u, v, w, z in zip(a, b, c, d)
            )
    if not closed:
        yield tuple(round(v * SUPERSAMPLE) for v in points[-1])


