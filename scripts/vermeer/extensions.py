"""Donor mattes traced on the 1536 × 1024 extended studio artwork."""

from PIL import Image, ImageChops, ImageDraw, ImageFilter

EXTENDED_SIZE = (1536, 1024)
PHOTO_SIZE = (1643, 2009)
PHOTO_TRACE_SIZE = (822, 1005)
SUPERSAMPLE = 3


def curtain_mask() -> Image.Image:
    """Return the tapestry, its tieback, and the foreground chair."""
    return _matte(_CURTAIN)


def chair_mask() -> Image.Image:
    """Return the rear chair with its open frame and arms cut out."""
    return _matte((_REAR_CHAIR,), _CHAIR_OPENINGS)


def front_chair_mask() -> Image.Image:
    """Return the visible foreground chair on the original photograph."""
    return _matte((_FRONT_CHAIR,), output_size=PHOTO_SIZE, trace_size=PHOTO_TRACE_SIZE)


def dark_cloth_mask() -> Image.Image:
    """Return the dark table drape on the original photograph."""
    cloth = _matte((_DARK_CLOTH,), output_size=PHOTO_SIZE, trace_size=PHOTO_TRACE_SIZE)
    chair_interior = front_chair_mask().filter(ImageFilter.MinFilter(5))
    return ImageChops.subtract(cloth, chair_interior)


def _matte(
    shapes, openings=(), *, output_size=EXTENDED_SIZE, trace_size=EXTENDED_SIZE
) -> Image.Image:
    size = tuple(dimension * SUPERSAMPLE for dimension in output_size)
    scale_x = size[0] / trace_size[0]
    scale_y = size[1] / trace_size[1]
    mask = Image.new("L", size)
    draw = ImageDraw.Draw(mask)
    for polygons, opacity in ((shapes, 255), (openings, 0)):
        for polygon in polygons:
            draw.polygon(
                [(round(x * scale_x), round(y * scale_y)) for x, y in polygon],
                fill=opacity,
            )
    return mask.resize(output_size, Image.Resampling.LANCZOS)


