"""Silhouette mattes for the 1643 × 2009 photograph of Vermeer's studio."""

from PIL import Image, ImageChops, ImageDraw, ImageFilter

PHOTO_SIZE = (1643, 2009)
TRACE_SIZE = (822, 1005)
SUPERSAMPLE = 3


def masks() -> dict[str, Image.Image]:
    """Return grayscale mattes in back-to-front order."""
    painter = _matte(_PAINTER, _STOOL_OPENINGS)
    easel = _matte(_EASEL, _EASEL_OPENINGS)
    # Keep a narrow overlap where the painter covers the easel.
    easel = ImageChops.subtract(easel, painter.filter(ImageFilter.MinFilter(7)))
    return {
        "model": _matte(_MODEL),
        "easel": easel,
        "painter": painter,
        "table": _matte(_TABLE),
        "curtain": _matte(_CURTAIN),
    }


def _matte(shapes, openings=()):
    size = tuple(dimension * SUPERSAMPLE for dimension in PHOTO_SIZE)
    horizontal_scale = size[0] / TRACE_SIZE[0]
    vertical_scale = size[1] / TRACE_SIZE[1]
    matte = Image.new("L", size)
    draw = ImageDraw.Draw(matte)
    for polygons, opacity in ((shapes, 255), (openings, 0)):
        for polygon in polygons:
            draw.polygon(
                [(round(x * horizontal_scale), round(y * vertical_scale)) for x, y in polygon],
                fill=opacity,
            )
    return matte.resize(PHOTO_SIZE, Image.Resampling.LANCZOS)


