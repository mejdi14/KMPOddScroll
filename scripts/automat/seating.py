def _draw_group(objects):
    size = tuple(length * SUPERSAMPLE for length in SIZE)
    alpha = Image.new("L", size)
    for polygons in objects:
        layer = Image.new("L", size)
        draw = ImageDraw.Draw(layer)
        for index, polygon in enumerate(polygons):
            points = [(x * SUPERSAMPLE, y * SUPERSAMPLE) for x, y in polygon]
            draw.polygon(points, fill=255 if index == 0 else 0)
        alpha.paste(255, mask=layer)
    return alpha.resize(SIZE, Image.Resampling.BOX)


def masks():
    """Return the nearer and farther seating mattes in artwork coordinates."""
    return _draw_group(FRONT), _draw_group(FAR)
