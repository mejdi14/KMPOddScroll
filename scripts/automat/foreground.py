def _rasterize(polygons):
    width, height = SIZE
    alpha = Image.new("L", (width * SUPERSAMPLE, height * SUPERSAMPLE))
    draw = ImageDraw.Draw(alpha)
    for outline in polygons:
        points = [(x * SUPERSAMPLE, y * SUPERSAMPLE) for x, y in outline]
        draw.polygon(points, fill=255)
    return alpha.resize(SIZE, Image.Resampling.BOX)


def mask():
    """Return the union of the visible woman, chairs, table and cup."""
    return _rasterize(LEFT_CHAIR + RIGHT_CHAIR + REAR_CHAIR + WOMAN + TABLE)


def left_chair_mask():
    """Return the chair nearest the viewer, including the rail over the table."""
    return _rasterize(LEFT_CHAIR)
